// Builds the ordered, reviewable LEGACY (derived-schema) staging install files from supabase/staging/manifest.json.
// SUPERSEDED by the Stage 4 production-equivalent package in supabase/staging/install/. These legacy files must NOT be run after a
// production-schema restore; they are kept only as evidence and for the historical conflict tests.
//   node scripts/build-staging-install.mjs          write supabase/staging/legacy_install/NN_name.sql
//   node scripts/build-staging-install.mjs --check  fail if the committed legacy files differ from a fresh build
// It only reads repository files and writes files inside supabase/staging/legacy_install/. It never connects to any database.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const manifest = JSON.parse(readFileSync(join(root, 'supabase/staging/manifest.json'), 'utf8'));
const outDir = join(root, 'supabase/staging/legacy_install');

export function buildInstallFiles() {
  const files = new Map();
  for (const step of manifest.steps) {
    const source = readFileSync(join(root, step.source), 'utf8').replace(/\r\n/g, '\n');
    let body = source;
    if (step.mode === 'excerpt') {
      const start = source.indexOf(step.from);
      const end = source.indexOf(step.to, start);
      if (start < 0 || end < 0) throw new Error(`staging manifest step ${step.step}: excerpt markers not found in ${step.source}`);
      body = source.slice(start, end).trimEnd() + '\n';
    } else if (step.mode !== 'full') {
      throw new Error(`staging manifest step ${step.step}: unknown mode ${step.mode}`);
    }
    const digest = createHash('sha256').update(source).digest('hex').slice(0, 16);
    for (const { from, to } of step.replace ?? []) {
      if (body.split(from).length !== 2) throw new Error(`staging manifest step ${step.step}: replacement text must occur exactly once`);
      body = body.replace(from, () => to);
    }
    const banner = [
      `-- STAGING INSTALL STEP ${step.step}: ${step.name}${step.optional ? ' (OPTIONAL)' : ''}`,
      `-- TARGET : ${manifest.target.project} (ref ${manifest.target.ref}, ${manifest.target.region}) ONLY. Never production.`,
      `-- SOURCE : ${step.source}${step.mode === 'excerpt' ? ` (verbatim excerpt from "${step.from}" up to, not including, "${step.to}")` : step.replace ? ' (copy with the labelled replacement below)' : ' (verbatim copy)'}`,
      ...(step.replace ?? []).map(({ from, to }) => `-- REPLACED: ${from}  ->  ${to}`),
      `-- SHA-256: ${digest}... of the source file (LF-normalised)`,
      `-- WHY    : ${step.why}`,
      ...(step.requires ? [`-- REQUIRES: ${step.requires}`] : []),
      '-- STATUS : PROPOSAL ONLY. Generated by scripts/build-staging-install.mjs; edit the source or the manifest, never this copy.',
      '',
    ].join('\n');
    files.set(`${step.deferred ? 'deferred/' : ''}${step.step}_${step.name}.sql`, `${banner}\n${body}`);
  }
  return files;
}

const listSql = (dir) => (existsSync(dir) ? readdirSync(dir).filter((name) => name.endsWith('.sql')).sort() : []);

if (process.argv[1] && process.argv[1].endsWith('build-staging-install.mjs')) {
  const files = buildInstallFiles();
  if (process.argv.includes('--check')) {
    const existing = [...listSql(outDir), ...listSql(join(outDir, 'deferred')).map((name) => `deferred/${name}`)].sort();
    const expected = [...files.keys()].sort();
    let failed = JSON.stringify(existing) !== JSON.stringify(expected);
    for (const [name, content] of files) {
      if (!existsSync(join(outDir, name)) || readFileSync(join(outDir, name), 'utf8') !== content) failed = true;
    }
    if (failed) { console.error('Staging install files are stale. Run: npm run staging:build'); process.exit(1); }
    console.log(`Staging install files are up to date (${files.size} files).`);
  } else {
    mkdirSync(join(outDir, 'deferred'), { recursive: true });
    for (const dir of [outDir, join(outDir, 'deferred')]) for (const name of listSql(dir)) rmSync(join(dir, name));
    for (const [name, content] of files) writeFileSync(join(outDir, name), content);
    console.log(`Wrote ${files.size} files to supabase/staging/legacy_install/ (deferred steps in legacy_install/deferred/)`);
  }
}
