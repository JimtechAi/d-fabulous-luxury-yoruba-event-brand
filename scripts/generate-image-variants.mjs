import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { existsSync } from 'node:fs';
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import ffmpegPath from 'ffmpeg-static';

const execFileAsync = promisify(execFile);
const root = process.cwd();
const sourceDirectories = [
  'public/images/gallery',
  'public/images/services',
  'public/assets/about',
  'public/assets/services',
];
const widths = [400, 800, 1200, 1600];
const sourceExtensions = /\.(?:webp|jpe?g|png)$/i;

async function getDimensions(sourcePath) {
  let stderr = '';
  try {
    ({ stderr } = await execFileAsync(ffmpegPath, ['-hide_banner', '-i', sourcePath], { maxBuffer: 1024 * 1024 }));
  } catch (error) {
    stderr = error.stderr || '';
  }
  const match = stderr.match(/, (\d+)x(\d+)(?: |\[)/);
  return match ? { width: Number(match[1]), height: Number(match[2]) } : null;
}

async function getSources(directory) {
  const entries = await readdir(path.join(root, directory), { withFileTypes: true });
  const sources = [];
  for (const entry of entries) {
    if (!entry.isFile() || !sourceExtensions.test(entry.name)) continue;
    const relativePath = path.join(directory, entry.name);
    const filePath = path.join(root, relativePath);
    const fileStats = await stat(filePath);
    if (fileStats.size < 250 * 1024) continue;
    const dimensions = await getDimensions(filePath);
    if (!dimensions || dimensions.width <= 400) continue;
    sources.push({ relativePath, filePath, dimensions });
  }
  return sources;
}

const sources = (await Promise.all(sourceDirectories.map(getSources))).flat();
const generatedSources = [];

function toPublicUrl(relativePath) {
  return `/${relativePath.replace(/^public[\\/]/, '').replaceAll(path.sep, '/')}`;
}

for (const source of sources) {
  const parsed = path.parse(source.relativePath);
  for (const width of widths) {
    if (width >= source.dimensions.width) continue;
    const outputRelativePath = path.join(parsed.dir, `${parsed.name}-${width}w.webp`);
    const outputPath = path.join(root, outputRelativePath);
    if (!existsSync(outputPath)) {
      await mkdir(path.dirname(outputPath), { recursive: true });
      await execFileAsync(ffmpegPath, [
        '-y', '-hide_banner', '-loglevel', 'error', '-i', source.filePath,
        '-vf', `scale=${width}:-2`, '-c:v', 'libwebp', '-quality', '82', outputPath,
      ]);
    }
    generatedSources.push({ source: toPublicUrl(source.relativePath), src: toPublicUrl(outputRelativePath), width });
  }
}

const manifest = `// Generated by npm run media:variants. Only list files that exist in public/.\nexport const RESPONSIVE_IMAGE_VARIANTS: Record<string, { src: string; width: number }[]> = ${JSON.stringify(
  generatedSources.reduce((result, item) => {
    (result[item.source] ||= []).push({ src: item.src, width: item.width });
    return result;
  }, {}), null, 2
)};\n`;
await writeFile(path.join(root, 'src/lib/media-variants.ts'), manifest, 'utf8');
console.log(`Generated or confirmed ${generatedSources.length} responsive image variants for ${sources.length} originals.`);